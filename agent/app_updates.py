"""Signed self-updates for V-Agent.

Only releases signed with the maintainer's private Ed25519 key are accepted. The private key never
leaves the maintainer's PC (see scripts/release.py); the app embeds only the public key below.

A release on GitHub must contain three assets:
  * the installer                      (V-Agent_<version>_x64-setup.exe)
  * v-agent-update.json                (the manifest: version, installer name, size, sha256, notes)
  * v-agent-update.json.sig            (Ed25519 signature of the manifest bytes, base64)

Checks, in order: official host and repository, signature, newer version than the one running,
installer asset with the exact signed name and size, then the downloaded bytes' SHA-256.
"""
import base64
import hashlib
import json
import os
import re
import threading
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

from runtime_paths import DATA_ROOT

VERSION = '1.0.3'
# "owner/repository" on GitHub. Empty = updates are not configured yet (nothing is contacted).
REPOSITORY = 'IsValorum/V-Agent'
# Ed25519 public key (raw 32 bytes, base64). Generated by scripts/release.py --init-key.
PUBLIC_KEY = '7IJNw62M85MwNKY6mgnkYQbRu3O9Tb3CFWM5Wr4uWfI='
MANIFEST = 'v-agent-update.json'
USER_AGENT = 'V-Agent-Updater'
MAX_INSTALLER = 3 * 2**30

# Runs outside the desktop/core process tree, so neither the executable nor the
# packaged core is still locked when NSIS replaces them. Arguments travel in the
# environment, never as interpolated PowerShell code.
UPDATE_HELPER = r'''
$ErrorActionPreference = 'Stop'
$log = $env:V_AGENT_UPDATE_LOG
try {
    foreach ($pidText in @($env:V_AGENT_UPDATE_DESKTOP_PID, $env:V_AGENT_UPDATE_CORE_PID)) {
        $processId = 0
        if (-not [int]::TryParse($pidText, [ref]$processId) -or $processId -le 0) { throw 'Invalid process identifier.' }
        $process = Get-Process -Id $processId -ErrorAction SilentlyContinue
        if ($process -and -not $process.WaitForExit(90000)) { throw 'V-Agent did not close in time; the update was not installed.' }
    }
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $stream = [System.IO.File]::OpenRead($env:V_AGENT_UPDATE_INSTALLER)
    try { $actualHash = [BitConverter]::ToString($sha.ComputeHash($stream)).Replace('-', '').ToLowerInvariant() } finally { $stream.Dispose(); $sha.Dispose() }
    if ($actualHash -ne $env:V_AGENT_UPDATE_SHA256) { throw 'The downloaded installer changed after verification.' }
    $setup = Start-Process -FilePath $env:V_AGENT_UPDATE_INSTALLER -ArgumentList '/S','/UPDATE' -Wait -PassThru
    if ($setup.ExitCode -ne 0) { throw "The installer failed (exit code $($setup.ExitCode))." }
    $exe = Get-Item -LiteralPath $env:V_AGENT_UPDATE_EXE
    if ($exe.VersionInfo.ProductVersion -ne $env:V_AGENT_UPDATE_VERSION) { throw 'The installer finished but the expected version was not installed.' }
    Add-Content -LiteralPath $log -Value "$(Get-Date -Format o) Installed $($env:V_AGENT_UPDATE_VERSION)"
    Start-Process -FilePath $exe.FullName | Out-Null
} catch {
    $message = "V-Agent could not be updated: $($_.Exception.Message)"
    try { Add-Content -LiteralPath $log -Value "$(Get-Date -Format o) $message" } catch {}
    try { Add-Type -AssemblyName System.Windows.Forms; [System.Windows.Forms.MessageBox]::Show($message, 'V-Agent', 'OK', 'Error') | Out-Null } catch {}
}
'''


def parse_version(value):
    match = re.fullmatch(r'v?(\d+)\.(\d+)\.(\d+)', str(value or '').strip())
    if not match:
        raise ValueError('Invalid version: %r' % value)
    return tuple(int(part) for part in match.groups())


def verify_signature(manifest_bytes, signature_b64, public_key_b64=PUBLIC_KEY):
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    try:
        key = Ed25519PublicKey.from_public_bytes(base64.b64decode(public_key_b64, validate=True))
        key.verify(base64.b64decode(signature_b64.strip(), validate=True), manifest_bytes)
        return True
    except (InvalidSignature, ValueError):
        return False


def validate_manifest(manifest_bytes, signature_b64, current=VERSION, public_key_b64=PUBLIC_KEY):
    """Return the parsed manifest if it is authentic and newer; raise ValueError otherwise."""
    if not verify_signature(manifest_bytes, signature_b64, public_key_b64):
        raise ValueError('The update signature is not valid; it was not published by the V-Agent maintainer.')
    data = json.loads(manifest_bytes.decode('utf-8'))
    installer = data.get('installer') or {}
    if data.get('product') != 'V-Agent' or not isinstance(installer, dict):
        raise ValueError('The update manifest is not for V-Agent.')
    if not re.fullmatch(r'V-Agent_[\w.-]+-setup\.exe', str(installer.get('name', ''))):
        raise ValueError('Unexpected installer name in the update manifest.')
    if not re.fullmatch(r'[0-9a-f]{64}', str(installer.get('sha256', ''))):
        raise ValueError('The update manifest has no valid checksum.')
    if not isinstance(installer.get('size'), int) or not 0 < installer['size'] <= MAX_INSTALLER:
        raise ValueError('The update manifest has an invalid size.')
    data['newer'] = parse_version(data.get('version')) > parse_version(current)
    return data


class AppUpdates:
    def __init__(self, repository=None):
        self.repository = REPOSITORY if repository is None else repository
        self.root = DATA_ROOT / 'app-updates'
        self.lock = threading.RLock()
        self.state = {'version': VERSION, 'repository': self.repository, 'configured': bool(self.repository),
                      'checked_at': 0, 'available': None, 'error': '', 'busy': False, 'progress': None, 'ready': None}

    def snapshot(self):
        with self.lock:
            return json.loads(json.dumps(self.state))

    def _get(self, url, limit):
        parts = urllib.parse.urlsplit(url)
        allowed = parts.scheme == 'https' and (
            parts.hostname == 'api.github.com' and parts.path.startswith('/repos/' + self.repository + '/')
            or parts.hostname == 'github.com' and parts.path.startswith('/' + self.repository + '/releases/download/'))
        if not allowed:
            raise ValueError('Refusing a download outside the official V-Agent repository.')
        request = urllib.request.Request(url, headers={'User-Agent': USER_AGENT, 'Accept': 'application/vnd.github+json'})
        with urllib.request.urlopen(request, timeout=20) as response:
            data = response.read(limit + 1)
        if len(data) > limit:
            raise ValueError('Unexpectedly large response.')
        return data

    def check(self):
        if not self.repository:
            with self.lock:
                self.state.update(error='', available=None, checked_at=time.time())
            return self.snapshot()
        with self.lock:
            if self.state['busy']:
                return self.snapshot()
            self.state.update(busy=True, error='')
        try:
            # Highest published app version (by number, not by date): minor "components-*" releases share
            # the repository but carry no installer, so GitHub's "latest" is not necessarily an app update.
            candidates = [r for r in json.loads(self._get('https://api.github.com/repos/%s/releases?per_page=30' % self.repository, 2**21))
                          if not r.get('draft') and not r.get('prerelease') and not str(r.get('tag_name', '')).startswith('components-')]
            def number(r):
                try:
                    return parse_version(str(r.get('tag_name', '')).lstrip('vV'))
                except ValueError:
                    return (-1, -1, -1)
            release = max(candidates, key=number, default=None)
            if release is None:
                with self.lock:
                    self.state.update(available=None, checked_at=time.time())
                return self.snapshot()
            assets = {a.get('name'): a for a in release.get('assets') or []}
            if MANIFEST not in assets or MANIFEST + '.sig' not in assets:
                raise ValueError('The latest release has no signed update manifest.')
            manifest = self._get(assets[MANIFEST]['browser_download_url'], 64 * 1024)
            signature = self._get(assets[MANIFEST + '.sig']['browser_download_url'], 4096).decode('ascii', 'replace')
            data = validate_manifest(manifest, signature)
            installer = assets.get(data['installer']['name'])
            if not installer or installer.get('size') != data['installer']['size']:
                raise ValueError('The installer published on GitHub does not match the signed manifest.')
            data['installer']['url'] = installer['browser_download_url']
            data['release_url'] = release.get('html_url', '')
            with self.lock:
                previous=self.state.get('available') or {}
                previous_hash=(previous.get('installer') or {}).get('sha256')
                if not data['newer'] or previous_hash!=data['installer']['sha256']:
                    self.state.update(ready=None,progress=None)
                self.state.update(available=data if data['newer'] else None, checked_at=time.time())
        except urllib.error.HTTPError as error:
            # 404: the repository is still private or not created; there is simply nothing published.
            with self.lock:
                self.state.update(available=None, error='' if error.code == 404 else str(error)[:300], checked_at=time.time())
        except Exception as error:
            with self.lock:
                self.state.update(error=str(error)[:300], checked_at=time.time())
        finally:
            with self.lock:
                self.state['busy'] = False
        return self.snapshot()

    def download(self):
        """Download the signed installer and verify it; returns its path (not executed here)."""
        with self.lock:
            update = self.state.get('available')
            if not update or self.state['busy']:
                raise ValueError('There is no verified update to install.')
            self.state.update(busy=True, error='', progress={'received': 0, 'total': update['installer']['size']})
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            target = self.root / update['installer']['name']
            partial = target.with_suffix('.part')
            parts = urllib.parse.urlsplit(update['installer']['url'])
            if parts.scheme != 'https' or parts.hostname != 'github.com' or not parts.path.startswith('/' + self.repository + '/releases/download/'):
                raise ValueError('Refusing a download outside the official V-Agent repository.')
            digest = hashlib.sha256(); size = 0
            request = urllib.request.Request(update['installer']['url'], headers={'User-Agent': USER_AGENT})
            with urllib.request.urlopen(request, timeout=60) as response, partial.open('wb') as output:
                while chunk := response.read(2**20):
                    size += len(chunk)
                    if size > update['installer']['size']:
                        raise ValueError('The installer is larger than the signed size.')
                    output.write(chunk); digest.update(chunk)
                    with self.lock:
                        self.state['progress']['received'] = size
            if size != update['installer']['size'] or digest.hexdigest() != update['installer']['sha256']:
                partial.unlink(missing_ok=True)
                raise ValueError('The downloaded installer does not match the signed checksum; it was discarded.')
            partial.replace(target)
            with self.lock:
                self.state['ready'] = str(target)
            return target
        except Exception as error:
            with self.lock:
                self.state['error'] = str(error)[:300]
            raise
        finally:
            with self.lock:
                self.state['busy'] = False

    def launch(self):
        """Hand the verified update to a helper which waits for V-Agent to exit."""
        import subprocess
        with self.lock:
            ready, update = self.state.get('ready'), self.state.get('available')
        if not ready or not update:
            raise ValueError('Download the update first.')
        path = Path(ready)
        if hashlib.sha256(path.read_bytes()).hexdigest() != update['installer']['sha256']:
            raise ValueError('The installer changed after it was verified; it was not started.')
        desktop_pid = os.environ.get('V_AGENT_DESKTOP_PID', '')
        desktop_exe = Path(os.environ.get('V_AGENT_DESKTOP_EXE', ''))
        if not desktop_pid.isdigit() or int(desktop_pid) <= 0 or not desktop_exe.is_file() or desktop_exe.name.lower() != 'v-agent.exe':
            raise ValueError('Automatic installation is only available in the V-Agent desktop application.')
        version = str(update.get('version', ''))
        if parse_version(version) <= parse_version(VERSION):
            raise ValueError('The update is not newer than the installed version.')
        log = DATA_ROOT / 'logs' / 'app-update.log'
        log.parent.mkdir(parents=True, exist_ok=True)
        env = os.environ.copy()
        env.update(V_AGENT_UPDATE_DESKTOP_PID=desktop_pid, V_AGENT_UPDATE_CORE_PID=str(os.getpid()),
                   V_AGENT_UPDATE_INSTALLER=str(path.resolve()), V_AGENT_UPDATE_SHA256=update['installer']['sha256'],
                   V_AGENT_UPDATE_EXE=str(desktop_exe.resolve()), V_AGENT_UPDATE_VERSION=version, V_AGENT_UPDATE_LOG=str(log))
        env['V_AGENT_UPDATE_HELPER'] = base64.b64encode(UPDATE_HELPER.encode('utf-16le')).decode('ascii')
        # An intermediate process exits before the desktop kills its core process tree;
        # the actual helper is therefore no longer a descendant of the core.
        starter = "$ErrorActionPreference='Stop'; Start-Process -FilePath powershell.exe -WindowStyle Hidden -ArgumentList @('-NoProfile','-NonInteractive','-EncodedCommand',$env:V_AGENT_UPDATE_HELPER) | Out-Null"
        encoded = base64.b64encode(starter.encode('utf-16le')).decode('ascii')
        try:
            result = subprocess.run(['powershell.exe', '-NoProfile', '-NonInteractive', '-EncodedCommand', encoded],
                                    env=env, close_fds=True, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                    stderr=subprocess.DEVNULL, creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0), timeout=15)
        except subprocess.TimeoutExpired as error:
            raise OSError('Starting the update helper timed out.') from error
        if result.returncode:
            raise OSError('Could not start the update helper.')
        return {'launched': True}


UPDATES = AppUpdates()
